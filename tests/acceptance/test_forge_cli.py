ROOT = Path(__file__).resolve().parents[2]
TOOL_NAMES = {"read_file", "edit_file", "write_file", "grep", "glob", "bash"}


def write_script(dirpath: Path, turns: list) -> Path:
    path = dirpath / "script.json"
    path.write_text(json.dumps({"turns": turns}), encoding="utf-8")
    return path


def run_forge(workspace: Path, args: list[str], env: dict | None = None) -> subprocess.CompletedProcess:
    merged = os.environ.copy()
    merged["PYTHONPATH"] = str(ROOT)
    merged.pop("FORGE_API_KEY", None)
    merged.pop("FORGE_MODEL", None)
    merged.pop("FORGE_BASE_URL", None)
    merged.pop("FORGE_PROVIDER", None)
    merged.pop("FORGE_HOME", None)
    merged.pop("FORGE_MAX_TOOL_OUTPUT", None)
    if env:
        merged.update(env)
    return subprocess.run(
        [sys.executable, "-m", "forge", *args],
        cwd=workspace,
        env=merged,
        text=True,
        capture_output=True,
        timeout=30,
    )


def trace_requests(path: Path) -> list[dict]:
    lines = [ln for ln in path.read_text(encoding="utf-8").splitlines() if ln.strip()]
    return [json.loads(ln) for ln in lines]


def assert_ok(proc: subprocess.CompletedProcess) -> None:
    assert proc.returncode == 0, proc.stderr + proc.stdout


class CapturingHandler(BaseHTTPRequestHandler):
    bodies: list
    paths: list
    headers: list
    responses: list

    def log_message(self, fmt, *args):
        return

    def do_POST(self):
        length = int(self.headers.get("Content-Length", "0"))
        raw = self.rfile.read(length)
        self.bodies.append(json.loads(raw.decode("utf-8") or "{}"))
        self.paths.append(self.path)
        self.headers.append({k.lower(): v for k, v in self.headers.items()})
        payload, status = self.responses.pop(0)
        data = json.dumps(payload).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        self.wfile.write(data)


def serve(responses: list):
    sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    sock.bind(("127.0.0.1", 0))
    port = sock.getsockname()[1]
    sock.close()
    handler = type(
        "Handler",
        (CapturingHandler,),
        {"bodies": [], "paths": [], "headers": [], "responses": list(responses)},
    )
    server = ThreadingHTTPServer(("127.0.0.1", port), handler)
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    return server, handler, port


def openai_text(text: str) -> dict:
    return {"choices": [{"message": {"role": "assistant", "content": text}}]}


def openai_tool(name: str, arguments: dict, call_id: str = "call_1") -> dict:
    return {
        "choices": [
            {
                "message": {
                    "role": "assistant",
                    "content": None,
                    "tool_calls": [
                        {
                            "id": call_id,
                            "type": "function",
                            "function": {"name": name, "arguments": json.dumps(arguments)},
                        }
                    ],
                }
            }
        ]
    }


def anthropic_text(text: str) -> dict:
    return {"content": [{"type": "text", "text": text}], "stop_reason": "end_turn"}


def anthropic_tool(name: str, payload: dict, tool_id: str = "tool_1") -> dict:
    return {
        "content": [{"type": "tool_use", "id": tool_id, "name": name, "input": payload}],
        "stop_reason": "tool_use",
    }


