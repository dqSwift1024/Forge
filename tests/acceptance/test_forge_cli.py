def test_session_jsonl_records_tools(tmp_path: Path):
    workspace = tmp_path / "ws"
    workspace.mkdir()
    (workspace / "app.py").write_text("v = 1\n", encoding="utf-8")
    script = write_script(
        tmp_path,
        [
            {"type": "tool", "name": "read_file", "input": {"path": "app.py"}},
            {"type": "tool", "name": "edit_file", "input": {"path": "app.py", "old": "v = 1", "new": "v = 2"}},
            {"type": "message", "text": "ok"},
        ],
    )
    proc = run_forge(
        workspace,
        [
            "run",
            "--provider",
            "fake",
            "--script",
            str(script),
            "--permission",
            "bypass",
            "--session-id",
            "sess1",
            "-p",
            "edit",
        ],
    )
    assert_ok(proc)
    lines = [
        json.loads(ln)
        for ln in (workspace / ".forge" / "sessions" / "sess1.jsonl").read_text(encoding="utf-8").splitlines()
        if ln.strip()
    ]
    tools = [row["tool"] for row in lines if "tool" in row]
    assert "read_file" in tools
    assert "edit_file" in tools
    assert all(isinstance(row.get("ok"), bool) for row in lines if "tool" in row)
